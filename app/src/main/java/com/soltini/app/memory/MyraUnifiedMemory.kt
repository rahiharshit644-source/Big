    fun saveDiaryEntry(
        title: String,
        content: String,
        mood: String = "NEUTRAL",
        category: String = "NOTE",
        tags: List<String> = emptyList(),
        isAutoGenerated: Boolean = false,
        dateMillis: Long = System.currentTimeMillis()
    ): DiaryEntry {
        val db = writableDatabase
        val id = UUID.randomUUID().toString()
        val sdf = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault())
        val dateString = sdf.format(Date(dateMillis))

        val cv = ContentValues().apply {
            put("id", id)
            put("title", title.trim())
            put("content", content.trim())
            put("date_millis", dateMillis)
            put("date_string", dateString)
            put("mood", mood.uppercase(Locale.ROOT))
            put("category", category.uppercase(Locale.ROOT))
            put("tags", tags.joinToString(","))
            put("is_auto_generated", if (isAutoGenerated) 1 else 0)
            put("created_at", System.currentTimeMillis())
        }
        db.insertWithOnConflict(TABLE_DIARY, null, cv, SQLiteDatabase.CONFLICT_REPLACE)

        return DiaryEntry(
            id = id,
            title = title.trim(),
            content = content.trim(),
            dateMillis = dateMillis,
            dateString = dateString,
            mood = mood.uppercase(Locale.ROOT),
            category = category.uppercase(Locale.ROOT),
            tags = tags,
            isAutoGenerated = isAutoGenerated,
            createdAt = System.currentTimeMillis()
        )
    }

    fun getAllDiaryEntries(): List<DiaryEntry> {
        val db = readableDatabase
        val list = mutableListOf<DiaryEntry>()
        val cursor = db.rawQuery(
            "SELECT * FROM $TABLE_DIARY ORDER BY date_millis DESC, created_at DESC",
            null
        )
        cursor.use {
            while (it.moveToNext()) {
                list.add(cursorToDiaryEntry(it))
            }
        }
        return list
    }

    fun getDiaryEntriesForDate(dateString: String): List<DiaryEntry> {
