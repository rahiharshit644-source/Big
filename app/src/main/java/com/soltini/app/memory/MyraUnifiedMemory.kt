    fun recordTurn(sender: String, text: String, id: String = UUID.randomUUID().toString()) {
        val trimmed = text.trim()
        if (trimmed.isBlank()) return

        val db = writableDatabase
        val cv = ContentValues().apply {
            put("id", id)
            put("sender", sender)
            put("text", trimmed)
            put("timestamp", System.currentTimeMillis())
        }
        db.insertWithOnConflict(TABLE_TURNS, null, cv, SQLiteDatabase.CONFLICT_REPLACE)
    }

    fun getRecentTurns(limit: Int = 30): List<ConversationTurn> {
        val list = mutableListOf<ConversationTurn>()
        val db = readableDatabase
        db.query(
            TABLE_TURNS,
            null,
            null,
            null,
            null,
            null,
            "timestamp DESC",
            limit.toString()
        ).use { cursor ->
            while (cursor.moveToNext()) {
                list.add(
                    ConversationTurn(
                        id = cursor.getString(cursor.getColumnIndexOrThrow("id")),
                        sender = cursor.getString(cursor.getColumnIndexOrThrow("sender")),
                        text = cursor.getString(cursor.getColumnIndexOrThrow("text")),
                        timestamp = cursor.getLong(cursor.getColumnIndexOrThrow("timestamp"))
                    )
                )
            }
        }
        return list.reversed()
    }

    fun recordSessionSummary(
        summary: String,
        keyPoints: List<String> = emptyList(),
        startedAt: Long = System.currentTimeMillis(),
        endedAt: Long = System.currentTimeMillis()
    ) {
        val trimmed = summary.trim()
        if (trimmed.isBlank()) return

        val db = writableDatabase
        val cv = ContentValues().apply {
            put("session_id", UUID.randomUUID().toString())
            put("started_at", startedAt)
            put("ended_at", endedAt)
            put("summary", trimmed)
            put("key_points", keyPoints.joinToString(" || "))
        }
        db.insert(TABLE_SESSIONS, null, cv)
        Log.i(TAG, "Recorded session summary: $trimmed")
    }

    fun getRecentSessionSummaries(limit: Int = 5): List<PastConversationRecap> {
        val list = mutableListOf<PastConversationRecap>()
        val db = readableDatabase
        db.query(
            TABLE_SESSIONS,
            null,
            null,
            null,
            null,
            null,
            "ended_at DESC",
            limit.toString()
        ).use { cursor ->
            while (cursor.moveToNext()) {
                val kpRaw = cursor.getString(cursor.getColumnIndexOrThrow("key_points")) ?: ""
                val points = if (kpRaw.isNotBlank()) kpRaw.split(" || ") else emptyList()
                list.add(
                    PastConversationRecap(
                        sessionId = cursor.getString(cursor.getColumnIndexOrThrow("session_id")),
                        startedAt = cursor.getLong(cursor.getColumnIndexOrThrow("started_at")),
                        endedAt = cursor.getLong(cursor.getColumnIndexOrThrow("ended_at")),
                        summary = cursor.getString(cursor.getColumnIndexOrThrow("summary")),
                        keyPoints = points
                    )
                )
            }
        }
        return list
    }

    /**
     * Automatically reviews recent conversation turns and creates a session summary if needed.
     */
    fun autoSummarizeSessionIfDue() {
        val turns = getRecentTurns(limit = 20)
        if (turns.size < 4) return // Not enough conversation to summarize

        val userTurns = turns.filter { it.sender == "USER" }.map { it.text }
        val agentTurns = turns.filter { it.sender == "MYRA" || it.sender == "GEMINI" }.map { it.text }

        if (userTurns.isEmpty()) return

        val mainTopics = userTurns.takeLast(4).joinToString("; ")
        val summary = "Discussed: $mainTopics"
        val firstTime = turns.first().timestamp
        val lastTime = turns.last().timestamp

        recordSessionSummary(
            summary = summary,
            keyPoints = userTurns.takeLast(3),
            startedAt = firstTime,
            endedAt = lastTime
        )
    }

