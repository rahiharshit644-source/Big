    /**
     * Builds a comprehensive Markdown block injected directly into Myra's system instruction.
     * Contains:
     *   - User identity & core facts
     *   - Preferences & habits
     *   - Active reminders & upcoming plans
     *   - Past conversation recaps & previous topics discussed
     *   - Clear instructions on how Myra should reference previous talks and use memory tools.
     */
    fun buildSystemPromptContext(): String {
        val memories = getAllMemories()
        val recaps = getRecentSessionSummaries(limit = 4)
        val recentTurns = getRecentTurns(limit = 10)

        val sb = StringBuilder()
        sb.append("\n\n### 🧠 MYRA'S ACTIVE PERMANENT MEMORY & PAST CONVERSATION HISTORY:\n")

        // 1. Facts & Profile
        val facts = memories.filter { it.category == "PERSON" || it.category == "FACT" || it.category == "PROJECT" }
        if (facts.isNotEmpty()) {
            sb.append("\n[USER IDENTITY & KNOWN FACTS]:\n")
            for (f in facts.take(8)) {
                sb.append("• ${f.content}\n")
            }
        }

        // 2. Preferences
        val prefs = memories.filter { it.category == "PREFERENCE" || it.category == "HABIT" }
        if (prefs.isNotEmpty()) {
            sb.append("\n[USER PREFERENCES & HABITS]:\n")
            for (p in prefs.take(6)) {
                sb.append("• ${p.content}\n")
            }
        }

        // 3. Active Reminders & Important Topics
        val reminders = memories.filter { it.category == "REMINDER" || it.category == "NOTE" }
        if (reminders.isNotEmpty()) {
            sb.append("\n[ACTIVE REMINDERS & IMPORTANT UPCOMING TOPICS]:\n")
            for (r in reminders.take(6)) {
                sb.append("• ⏰ ${r.content}\n")
            }
