    /**
     * Saves a memory item with automatic deduplication.
     * If an existing memory has similar key or content, updates it.
     */
    fun saveMemory(
        content: String,
        category: String = "FACT",
        importance: Float = 0.8f,
        tags: List<String> = emptyList(),
        keyName: String? = null
    ): UnifiedMemory {
        val trimmed = content.trim()
        if (trimmed.isBlank()) {
            return UnifiedMemory(content = "")
        }

        val normalizedCategory = category.uppercase(Locale.ROOT).trim().ifBlank { "FACT" }
        val derivedKey = (keyName ?: deriveKey(trimmed, normalizedCategory)).lowercase(Locale.ROOT).trim()

        val autoTags = (tags + extractSearchTokens(trimmed) + listOf(normalizedCategory.lowercase(Locale.ROOT)))
            .distinct()
            .filter { it.isNotBlank() }

        val db = writableDatabase
        val now = System.currentTimeMillis()

        // Check if an existing memory matches this key or has high overlap
        val existing = findExistingMemory(derivedKey, trimmed)
        val targetId = existing?.id ?: UUID.randomUUID().toString()
        val finalImportance = if (existing != null) maxOf(existing.importance, importance) else importance

        val cv = ContentValues().apply {
            put("id", targetId)
            put("category", normalizedCategory)
            put("key_name", derivedKey)
            put("content", trimmed)
            put("importance", finalImportance)
            put("updated_at", now)
            put("last_recalled_at", now)
            put("user_confirmed", 1)
            put("tags", autoTags.joinToString(","))
            if (existing == null) {
                put("created_at", now)
                put("recall_count", 0)
            }
        }

        if (existing != null) {
            db.update(TABLE_MEMORIES, cv, "id = ?", arrayOf(targetId))
            Log.i(TAG, "Updated existing memory [$targetId]: $trimmed")
        } else {
            db.insertWithOnConflict(TABLE_MEMORIES, null, cv, SQLiteDatabase.CONFLICT_REPLACE)
            Log.i(TAG, "Inserted new memory [$targetId]: $trimmed")
        }

        return UnifiedMemory(
            id = targetId,
            category = normalizedCategory,
            keyName = derivedKey,
            content = trimmed,
            importance = finalImportance,
            createdAt = existing?.createdAt ?: now,
            updatedAt = now,
            lastRecalledAt = now,
            recallCount = (existing?.recallCount ?: 0) + 1,
            userConfirmed = true,
            tags = autoTags
        )
    }

    private fun findExistingMemory(key: String, content: String): UnifiedMemory? {
        val db = readableDatabase

        // 1. Check exact key match for unique profile items (e.g. user_name, birthday)
        if (key.isNotBlank() && key != "general_fact") {
            db.query(
                TABLE_MEMORIES,
                null,
                "key_name = ?",
                arrayOf(key),
                null, null, null, "1"
            ).use { cursor ->
                if (cursor.moveToFirst()) return cursorToMemory(cursor)
            }
        }

        // 2. Check exact content match
        db.query(
            TABLE_MEMORIES,
            null,
            "content = ?",
            arrayOf(content),
            null, null, null, "1"
        ).use { cursor ->
            if (cursor.moveToFirst()) return cursorToMemory(cursor)
        }

        // 3. Substring / high-overlap check for short statements
        if (content.length > 8) {
            val prefix = content.take(30)
            db.query(
                TABLE_MEMORIES,
                null,
                "content LIKE ?",
                arrayOf("%$prefix%"),
                null, null, null, "1"
            ).use { cursor ->
                if (cursor.moveToFirst()) return cursorToMemory(cursor)
            }
        }

        return null
    }

    fun getAllMemories(): List<UnifiedMemory> {
        val list = mutableListOf<UnifiedMemory>()
        val db = readableDatabase
        db.query(
            TABLE_MEMORIES,
            null,
            null,
            null,
            null,
            null,
            "importance DESC, updated_at DESC"
        ).use { cursor ->
            while (cursor.moveToNext()) {
                list.add(cursorToMemory(cursor))
            }
        }
        return list
    }

    fun searchMemories(query: String, limit: Int = 10): List<UnifiedMemory> {
        val trimmed = query.trim()
        if (trimmed.isBlank()) return getAllMemories().take(limit)

        val tokens = extractSearchTokens(trimmed)
        val all = getAllMemories()

        // Score based on token matches, key matches, importance, and recency
        return all.map { memory ->
            var score = 0f
            val lowerContent = memory.content.lowercase(Locale.ROOT)
            val lowerKey = memory.keyName.lowercase(Locale.ROOT)
            val lowerCategory = memory.category.lowercase(Locale.ROOT)

            if (lowerContent.contains(trimmed.lowercase(Locale.ROOT))) {
                score += 50f
            }
            if (lowerKey.contains(trimmed.lowercase(Locale.ROOT))) {
                score += 30f
            }

            for (token in tokens) {
                if (lowerContent.contains(token)) score += 10f
                if (lowerKey.contains(token)) score += 15f
                if (lowerCategory.contains(token)) score += 5f
                if (memory.tags.any { it.contains(token, ignoreCase = true) }) score += 8f
            }

            score += memory.importance * 10f
            Pair(memory, score)
        }
            .filter { it.second > 0f }
            .sortedByDescending { it.second }
            .take(limit)
            .map { it.first }
    }

    fun deleteMemory(id: String): Boolean {
        val db = writableDatabase
        val rows = db.delete(TABLE_MEMORIES, "id = ?", arrayOf(id))
        return rows > 0
    }

    fun deleteMemoriesMatching(query: String): Int {
        val matches = searchMemories(query, limit = 50)
        var count = 0
        for (m in matches) {
            if (deleteMemory(m.id)) count++
        }
        return count
    }

    fun clearAllMemories(): Boolean {
        val db = writableDatabase
        db.delete(TABLE_MEMORIES, null, null)
        db.delete(TABLE_TURNS, null, null)
        db.delete(TABLE_SESSIONS, null, null)
        return true
    }

    fun updateMemory(id: String, newContent: String, newCategory: String? = null): Boolean {
        val db = writableDatabase
        val cv = ContentValues().apply {
            put("content", newContent.trim())
            if (!newCategory.isNullOrBlank()) {
                put("category", newCategory.uppercase(Locale.ROOT).trim())
            }
            put("updated_at", System.currentTimeMillis())
        }
        return db.update(TABLE_MEMORIES, cv, "id = ?", arrayOf(id)) > 0
    }

