    fun searchDiary(query: String): List<DiaryEntry> {
        val q = query.trim()
        if (q.isBlank()) return getAllDiaryEntries()
        val db = readableDatabase
        val list = mutableListOf<DiaryEntry>()
        val cursor = db.rawQuery(
            "SELECT * FROM $TABLE_DIARY WHERE title LIKE ? OR content LIKE ? OR tags LIKE ? ORDER BY date_millis DESC",
            arrayOf("%$q%", "%$q%", "%$q%")
        )
        cursor.use {
            while (it.moveToNext()) {
                list.add(cursorToDiaryEntry(it))
            }
        }
        return list
    }

    fun generateDailyRecapSummary(): DiaryEntry? {
        val sdf = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault())
        val todayStr = sdf.format(Date())
        val todayStart = Calendar.getInstance().apply {
            set(Calendar.HOUR_OF_DAY, 0)
            set(Calendar.MINUTE, 0)
            set(Calendar.SECOND, 0)
            set(Calendar.MILLISECOND, 0)
        }.timeInMillis

        // Get turns from today
