    /**
     * Extracts persistent facts from spoken or typed statements in Hindi, Hinglish, or English.
     */
    fun extractFactsFromText(text: String, isUser: Boolean = true): List<UnifiedMemory> {
        val cleaned = text.trim()
        if (cleaned.length < 4) return emptyList()

        val lower = cleaned.lowercase(Locale.ROOT)
        val extracted = mutableListOf<UnifiedMemory>()

        // 1. User Name Extraction
        // "mera naam rahul hai", "my name is rahul", "mujhe rahul bulao", "call me rahul"
        val nameRegexes = listOf(
            Regex("(?i)(?:mera naam|my name is|naam hai|call me|mujhe bulao)\\s+([a-zA-Z\\u0900-\\u097F]+)"),
            Regex("(?i)main\\s+([a-zA-Z\\u0900-\\u097F]+)\\s+hoon")
        )
        for (rx in nameRegexes) {
            rx.find(cleaned)?.let { match ->
                val name = match.groupValues[1].trim()
                if (name.length in 2..20 && !name.equals("hai", true) && !name.equals("hoon", true)) {
                    val mem = saveMemory(
                        content = "User ka naam $name hai.",
                        category = "PERSON",
                        importance = 1.0f,
                        keyName = "user_name"
                    )
                    extracted.add(mem)
                }
            }
        }

        // 2. Explicit "Remember that" / "Yaad rakhna" statements
        // "yaad rakhna kal exam hai", "remember that i hate spicy food"
        val rememberRegex = Regex("(?i)(?:yaad rakhna ki|yaad rakhna|yaad rakh|remember that|remember to|keep in mind that|hamesha yaad rakhna)\\s+(.+)")
        rememberRegex.find(cleaned)?.let { match ->
            val fact = match.groupValues[1].trim()
            if (fact.length > 3) {
                val category = if (fact.contains("kal", true) || fact.contains("tomorrow", true) || fact.contains("baje", true)) "REMINDER" else "FACT"
                val mem = saveMemory(
                    content = fact,
                    category = category,
                    importance = 0.95f,
                    keyName = "explicit_user_rule"
                )
                extracted.add(mem)
            }
        }

        // 3. User Preferences (Likes & Dislikes)
        // "mujhe coffee pasand hai", "i like dark chocolate", "meri favorite movie interstellar hai"
        if (lower.contains("pasand hai") || lower.contains("pasand nahi") || lower.contains("favorite") || lower.contains("i like") || lower.contains("i love") || lower.contains("i prefer")) {
            val mem = saveMemory(
                content = cleaned,
                category = "PREFERENCE",
                importance = 0.85f,
                keyName = "user_preference"
            )
            extracted.add(mem)
        }

        // 4. Family & Friends (Relationships)
        // "mera bhai rohit", "my friend sneha", "meri mummy ka naam"
        val relationKeywords = listOf("bhai", "sister", "dost", "friend", "mother", "father", "mummy", "papa", "wife", "husband", "brother")
        if (relationKeywords.any { lower.contains(it) }) {
            val mem = saveMemory(
                content = cleaned,
                category = "PERSON",
                importance = 0.85f,
                keyName = "family_and_friends"
            )
            extracted.add(mem)
        }

        // 5. Important Reminders & Upcoming Plans
        // "kal subah 8 baje uthna hai", "tomorrow is my interview", "somwar ko doctor ke paas jana hai"
        val reminderKeywords = listOf("kal", "tomorrow", "exam", "interview", "meeting", "flight", "train", "baje", "doctor", "medicine", "subah", "shaam")
        if (reminderKeywords.any { lower.contains(it) } && (lower.contains("hai") || lower.contains("jana") || lower.contains("karna") || lower.contains("have to") || lower.contains("need to"))) {
            val mem = saveMemory(
                content = cleaned,
                category = "REMINDER",
                importance = 0.90f,
                keyName = "active_plan"
            )
            extracted.add(mem)
        }

        return extracted
    }

