    private fun deriveKey(content: String, category: String): String {
        val lower = content.lowercase(Locale.ROOT)
        return when {
            lower.contains("naam") || lower.contains("name") -> "user_name"
            lower.contains("bhai") || lower.contains("brother") -> "user_brother"
            lower.contains("dost") || lower.contains("friend") -> "user_friend"
            lower.contains("pasand") || lower.contains("like") || lower.contains("favorite") -> "user_preference"
            lower.contains("exam") || lower.contains("interview") -> "user_exam"
            lower.contains("birthday") || lower.contains("janmdin") -> "user_birthday"
            lower.contains("kal") || lower.contains("tomorrow") -> "upcoming_schedule"
            else -> "${category.lowercase(Locale.ROOT)}_${UUID.randomUUID().toString().take(6)}"
        }
    }

    private fun extractSearchTokens(text: String): List<String> {
        val stopWords = setOf("hai", "ki", "ka", "ke", "ko", "mai", "main", "mera", "meri", "mere", "the", "a", "an", "is", "in", "to", "and", "or", "of", "for", "with", "ye", "wo")
        return text.lowercase(Locale.ROOT)
            .split(" ", ",", ".", "?", "!", ":", ";", "\n", "\t", "-", "_")
            .map { it.trim() }
            .filter { it.length > 2 && !stopWords.contains(it) }
            .distinct()
    }

    private fun cursorToMemory(cursor: android.database.Cursor): UnifiedMemory {
        val tagsRaw = cursor.getString(cursor.getColumnIndexOrThrow("tags")) ?: ""
        val tags = if (tagsRaw.isNotBlank()) tagsRaw.split(",") else emptyList()
        return UnifiedMemory(
            id = cursor.getString(cursor.getColumnIndexOrThrow("id")),
            category = cursor.getString(cursor.getColumnIndexOrThrow("category")),
            keyName = cursor.getString(cursor.getColumnIndexOrThrow("key_name")) ?: "",
            content = cursor.getString(cursor.getColumnIndexOrThrow("content")),
            importance = cursor.getFloat(cursor.getColumnIndexOrThrow("importance")),
            createdAt = cursor.getLong(cursor.getColumnIndexOrThrow("created_at")),
