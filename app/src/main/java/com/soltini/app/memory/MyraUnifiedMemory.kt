/**
 * UnifiedMemory
 *
 * Represents an atomic unit of permanent knowledge, user profile attribute,
 * preference, active reminder, or relationship fact.
 */
data class UnifiedMemory(
    val id: String = UUID.randomUUID().toString(),
    val category: String = "FACT", // FACT, PREFERENCE, REMINDER, PERSON, PROJECT, HABIT, NOTE
    val keyName: String = "",
    val content: String,
    val importance: Float = 0.8f, // 0.0 to 1.0 (0.9+ = critical fact / identity)
    val createdAt: Long = System.currentTimeMillis(),
    val updatedAt: Long = System.currentTimeMillis(),
    val lastRecalledAt: Long = System.currentTimeMillis(),
    val recallCount: Int = 0,
    val userConfirmed: Boolean = true,
    val tags: List<String> = emptyList()
)

data class PastConversationRecap(
    val sessionId: String = UUID.randomUUID().toString(),
    val startedAt: Long = System.currentTimeMillis(),
    val endedAt: Long = System.currentTimeMillis(),
    val summary: String,
    val keyPoints: List<String> = emptyList()
)

data class ConversationTurn(
    val id: String = UUID.randomUUID().toString(),
    val sender: String, // USER or MYRA
    val text: String,
    val timestamp: Long = System.currentTimeMillis()
)

data class DiaryEntry(
    val id: String = UUID.randomUUID().toString(),
    val title: String,
    val content: String,
    val dateMillis: Long = System.currentTimeMillis(),
    val dateString: String = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault()).format(Date()),
    val mood: String = "NEUTRAL",
    val category: String = "NOTE",
    val tags: List<String> = emptyList(),
    val isAutoGenerated: Boolean = false,
    val createdAt: Long = System.currentTimeMillis()
)

/**
 * MyraUnifiedMemory
 *
 * Single, reliable, unified persistent memory engine for Myra.
 * Features:
 *   1. 100% offline, local SQLite storage that survives app restarts, task kills, and reboots.
 *   2. Native Hindi, Hinglish, and English intelligent fact & preference extraction.
 *   3. Smart deduplication and update resolution (e.g. updating name or phone instead of duplicating).
 *   4. Past conversation recaps and session topic tracking so Myra always remembers what was discussed.
 *   5. Comprehensive context prompt formatting for Gemini Live and Myra Orchestrator.
 *   6. First-class tool support for voice interactions (save_memory, recall_memories, get_past_conversations, forget_memory).
 */
class MyraUnifiedMemory private constructor(context: Context) : SQLiteOpenHelper(
    context.applicationContext, DB_NAME, null, DB_VERSION
) {
    companion object {
        private const val TAG = "MyraUnifiedMemory"
        private const val DB_NAME = "myra_unified_memory.db"
        private const val DB_VERSION = 3

        private const val TABLE_MEMORIES = "unified_memories"
        private const val TABLE_SESSIONS = "conversation_sessions"
        private const val TABLE_TURNS = "conversation_turns"
        private const val TABLE_SCHEDULED_TASKS = "scheduled_tasks"
        private const val TABLE_DIARY = "daily_diary"

        @Volatile
        private var instance: MyraUnifiedMemory? = null

        fun getInstance(context: Context): MyraUnifiedMemory =
            instance ?: synchronized(this) {
                instance ?: MyraUnifiedMemory(context.applicationContext).also {
                    instance = it
                    CoroutineScope(Dispatchers.IO).launch {
                        it.ensureDeveloperProfileSeeded()
                    }
                }
            }
    }

