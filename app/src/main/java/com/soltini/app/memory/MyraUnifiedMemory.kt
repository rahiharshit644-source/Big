        val turnsToday = mutableListOf<ConversationTurn>()
        val turnCursor = db.rawQuery(
            "SELECT * FROM $TABLE_TURNS WHERE timestamp >= ? ORDER BY timestamp ASC",
            arrayOf(todayStart.toString())
        )
        turnCursor.use {
            while (it.moveToNext()) {
                turnsToday.add(
                    ConversationTurn(
                        id = it.getString(it.getColumnIndexOrThrow("id")),
                        sender = it.getString(it.getColumnIndexOrThrow("sender")),
                        text = it.getString(it.getColumnIndexOrThrow("text")),
                        timestamp = it.getLong(it.getColumnIndexOrThrow("timestamp"))
                    )
                )
            }
        }

        if (turnsToday.isEmpty()) return null

        // Get memories added today
        val memoriesToday = getAllMemories().filter { it.createdAt >= todayStart }

