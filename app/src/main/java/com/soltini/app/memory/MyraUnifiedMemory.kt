            sb.append("\n[USER'S DIARY & PERMANENT DAILY NOTES]:\n")
            for (d in diaryEntries) {
                sb.append("• [${d.dateString} - ${d.title}]: ${d.content.take(140)}\n")
            }
        }

        // 6. Memory & Diary Behavioral Rules
        sb.append("""

