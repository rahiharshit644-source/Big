        userMessages.take(6).forEach { msg ->
            sb.append("• $msg\n")
        }

        if (memoriesToday.isNotEmpty()) {
            sb.append("\nNaye facts aur preferences jo yaad rakhe:\n")
            memoriesToday.take(5).forEach { m ->
                sb.append("• ${m.content}\n")
            }
        }

        val displayDate = SimpleDateFormat("dd MMMM yyyy", Locale.getDefault()).format(Date())
        val title = "Daily Reflection - $displayDate"

        val existingToday = getDiaryEntriesForDate(todayStr).firstOrNull { it.isAutoGenerated }
